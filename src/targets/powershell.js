import { color, resolveScope, fitContrast, toTier, contrast, toHex } from '../theme.js'

// Style flags go first so output looks like "3;38;2;r;g;b", the usual SGR form.
// fg 'default' emits 39 so the text follows whichever terminal scheme is active.
// A truecolor fg must already be fitted to its contrast tier.
function sgr({ fg, bg, fontStyle = '' }) {
  const parts = []
  if (/italic/.test(fontStyle)) parts.push('3')
  if (/bold/.test(fontStyle)) parts.push('1')
  if (fg === 'default') parts.push('39')
  else if (fg) parts.push(`38;2;${fg.join(';')}`)
  if (bg) parts.push(`48;2;${bg.join(';')}`)
  return `"$e[${parts.join(';')}m"`
}

const archiveExtensions = ['.zip', '.tgz', '.gz', '.tar', '.nupkg', '.cab', '.7z']
const scriptExtensions = ['.ps1', '.psd1', '.psm1', '.ps1xml']
// In PATHEXT on Windows, so PowerShell paints them as executables; they are source files here
const pathextScriptExtensions = ['.js', '.jse', '.vbs', '.vbe', '.wsf', '.wsh']

export function generatePowerShell(theme) {
  const col = (key) => color(theme, key)
  const editorBg = col('editor.background')
  const editorFg = col('editor.foreground')
  // Tier 2 (accent) and tier 3 (quiet): see tiers in theme.js
  const accent = (role, rgb, fontStyle = '') => sgr({ fg: toTier(theme, role, 'accent', rgb, editorBg), fontStyle })
  const quiet = (role, rgb, fontStyle = '') => sgr({ fg: toTier(theme, role, 'quiet', rgb, editorBg), fontStyle })
  const accentKey = (role, key, fontStyle) => accent(role, col(key), fontStyle)
  // fontStyle undefined keeps the scope's own, '' drops it
  const accentScope = (role, name, fontStyle) => {
    const resolved = resolveScope(theme, name)
    return accent(role, resolved.rgb, fontStyle ?? resolved.fontStyle)
  }
  const quietScope = (role, name) => quiet(role, resolveScope(theme, name).rgb)

  // Selection and prediction highlights are backgrounds under normal text, so the background moves, not the text
  const selectable = (role, key) => {
    const bg = fitContrast(col(key), editorFg, 4.5)
    const ratio = contrast(editorFg, bg)
    if (ratio < 4.5) throw new Error(`${theme.slug}: ${role} ${toHex(bg)} behind ${toHex(editorFg)} is ${ratio.toFixed(2)}:1, below 4.5`)
    return bg
  }
  const progressBg = col('textLink.foreground')
  const progressFg = fitContrast(editorBg, progressBg, 4.5)
  if (contrast(progressFg, progressBg) < 4.5) throw new Error(`${theme.slug}: Progress.Style text is below 4.5:1`)

  const pairs = (list, indent) => list.map(([k, v]) => `${indent}${k} = ${v}`).join('\n')

  const base = [
    ['Default', sgr({ fg: 'default' })],
    ['Comment', quietScope('Comment', 'comment')],
    ['Keyword', accentScope('Keyword', 'keyword')],
    ['String', accentScope('String', 'string')],
    ['Number', accentScope('Number', 'constant.numeric')],
    ['Operator', accentScope('Operator', 'keyword.operator')],
    ['Variable', accentScope('Variable', 'variable')],
    ['Parameter', accentScope('Parameter', 'variable.parameter')],
    ['Command', accentScope('Command', 'entity.name.function')],
    ['Type', accentScope('Type', 'entity.name.type')],
    ['Member', accentScope('Member', 'support.type.property-name')],
    ['Emphasis', accentKey('Emphasis', 'textLink.foreground')],
    ['Error', accentKey('Error', 'terminal.ansiRed')],
    ['ContinuationPrompt', quietScope('ContinuationPrompt', 'punctuation.definition.comment')],
    ['Selection', sgr({ fg: 'default', bg: selectable('Selection', 'terminal.selectionBackground') })]
  ]
  const v21 = [['InlinePrediction', quietScope('InlinePrediction', 'comment')]]
  const v22 = [
    ['ListPrediction', accentKey('ListPrediction', 'textLink.foreground')],
    ['ListPredictionSelected', sgr({ bg: selectable('ListPredictionSelected', 'list.activeSelectionBackground') })]
  ]
  const v23 = [['ListPredictionTooltip', quietScope('ListPredictionTooltip', 'comment')]]

  const extensions = (names, style) =>
    names.map((n) => `      $PSStyle.FileInfo.Extension['${n}'] = ${style}`).join('\n')

  return `# ${theme.name}
# generated by harmonia-terminal, do not edit

& {
  $e = [char]27

  try {
    if (Get-Module PSReadLine) {
      $rlVersion = (Get-Module PSReadLine).Version
      $colors = @{
${pairs(base, '        ')}
      }
      if ($rlVersion -ge [version]'2.1') {
${pairs(v21, '        $colors.')}
      }
      if ($rlVersion -ge [version]'2.2') {
${pairs(v22, '        $colors.')}
      }
      if ($rlVersion -ge [version]'2.3') {
${pairs(v23, '        $colors.')}
      }
      Set-PSReadLineOption -Colors $colors -ErrorAction Stop
    }
  } catch {}

  try {
    if ($PSVersionTable.PSVersion -ge [version]'7.2') {
      $PSStyle.Formatting.TableHeader = ${accentScope('TableHeader', 'entity.name.type', 'bold')}
      $PSStyle.Formatting.FormatAccent = ${accentScope('FormatAccent', 'entity.name.type', 'bold')}
      $PSStyle.Formatting.CustomTableHeaderLabel = ${accentScope('CustomTableHeaderLabel', 'entity.name.type', 'italic')}
      $PSStyle.Formatting.Error = ${accentKey('Formatting.Error', 'terminal.ansiRed')}
      $PSStyle.Formatting.ErrorAccent = ${accentKey('ErrorAccent', 'terminal.ansiRed', 'bold')}
      $PSStyle.Formatting.Warning = ${accentKey('Warning', 'editorWarning.foreground')}
      $PSStyle.Formatting.Verbose = ${accentKey('Verbose', 'editorInfo.foreground')}
      $PSStyle.Formatting.Debug = ${quietScope('Debug', 'comment')}
      $formatting = $PSStyle.Formatting.PSObject.Properties
      if ($formatting['FeedbackName']) { $PSStyle.Formatting.FeedbackName = ${accentKey('FeedbackName', 'textLink.foreground')} }
      if ($formatting['FeedbackText']) { $PSStyle.Formatting.FeedbackText = ${sgr({ fg: 'default' })} }
      if ($formatting['FeedbackAction']) { $PSStyle.Formatting.FeedbackAction = ${accentScope('FeedbackAction', 'string', '')} }
      $PSStyle.Progress.Style = ${sgr({ fg: progressFg, bg: progressBg })}
      $PSStyle.FileInfo.Directory = ${accentKey('Directory', 'textLink.foreground', 'bold')}
      $PSStyle.FileInfo.SymbolicLink = ${accentKey('SymbolicLink', 'terminal.ansiCyan')}
      $PSStyle.FileInfo.Executable = ${accentScope('Executable', 'string', '')}
${extensions(archiveExtensions, accentScope('Extension archive', 'constant.numeric', ''))}
${extensions(scriptExtensions, accentScope('Extension script', 'keyword', ''))}
${extensions(pathextScriptExtensions, sgr({ fg: 'default' }))}
      $formatFile = Join-Path $PSScriptRoot 'harmonia.format.ps1xml'
      if (Test-Path $formatFile) { Update-FormatData -PrependPath $formatFile }
    }
  } catch {}
}
`
}
