import { color, resolveScope, toTier } from '../theme.js'

// Only the table view is replaced; widths, alignment and text match PowerShell 7.6's default "children" view.
// Dim/normal/accent colors are baked per variant because format files cannot read $PSStyle at load time.

const escapeXml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

// Quiet roles are metadata and dot-entries; accent roles are the colored text you read.
// A dot-directory is the folder hue in the quiet tier, so it stays blue where dotfiles are gray.
export function formatPalette(theme) {
  const col = (key) => color(theme, key)
  const bg = col('editor.background')
  const quiet = (role, rgb) => toTier(theme, role, 'quiet', rgb, bg)
  const accent = (role, rgb) => toTier(theme, role, 'accent', rgb, bg)
  return {
    quiet: {
      dim: quiet('dim', col('editorLineNumber.foreground')),
      muted: quiet('dotfile', resolveScope(theme, 'comment').rgb),
      softFolder: quiet('softFolder', col('textLink.foreground'))
    },
    accent: {
      folder: accent('folder', col('textLink.foreground')),
      flag: accent('flag', col('editorWarning.foreground')),
      link: accent('link', col('terminal.ansiCyan'))
    }
  }
}

export function generatePowerShellFormat(theme) {
  const { quiet, accent } = formatPalette(theme)
  // Parameter part of an SGR sequence, spliced into "$e[...m" inside the scriptblocks
  const code = (rgb) => `38;2;${rgb.join(';')}`

  const dim = code(quiet.dim)
  // Terminal default foreground, so it stays readable if the scheme is switched
  const normal = '39'
  const folder = code(accent.folder)
  const softFolder = code(quiet.softFolder)
  const accentFlag = code(accent.flag)
  const link = code(accent.link)
  const muted = code(quiet.muted)

  const script = (body) =>
    escapeXml(body.trim().replace(/^ {6}/gm, ''))
      .split('\n')
      .map((line) => `                  ${line}`.trimEnd())
      .join('\n')

  const mode = script(`
      $e = [char]27
      $o = foreach ($c in $_.ModeWithoutHardLink.ToCharArray()) {
        $s = if ($c -eq 'd') { '${folder}' } elseif ($c -in 'r', 'h', 's') { '${accentFlag}' } elseif ($c -eq 'l') { '${link}' } else { '${dim}' }
        "$e[\${s}m$c$e[0m"
      }
      $o -join ''
  `)
  const lastWrite = script(`
      $e = [char]27
      $s = if ($_.LastWriteTime.Date -eq [datetime]::Today) { '${normal}' } else { '${dim}' }
      "$e[\${s}m$($_.LastWriteTimeString)$e[0m"
  `)
  const length = script(`
      $e = [char]27
      $t = $_.LengthString
      if ($t) { "$e[${dim}m$t$e[0m" } else { $t }
  `)
  const name = script(`
      if ($_.Name.StartsWith('.') -and -not $_.LinkType) {
        $e = [char]27
        $s = if ($_.PSIsContainer) { '${softFolder}' } else { '${muted}' }
        "$e[\${s}m$($_.Name)$e[0m"
      } else {
        $_.NameString
      }
  `)
  const header = script(`
      $e = [char]27
      "    $e[${dim}mDirectory:$e[0m $e[${normal}m$($_.PSParentPath.Replace('Microsoft.PowerShell.Core\\FileSystem::', ''))$e[0m"
  `)

  const item = (body) => `              <TableColumnItem>
                <ScriptBlock>
${body}
                </ScriptBlock>
              </TableColumnItem>`

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${escapeXml(theme.name)} -->
<!-- generated by harmonia-terminal, do not edit -->
<Configuration>
  <ViewDefinitions>
    <View>
      <Name>children</Name>
      <ViewSelectedBy>
        <TypeName>System.IO.DirectoryInfo</TypeName>
        <TypeName>System.IO.FileInfo</TypeName>
      </ViewSelectedBy>
      <GroupBy>
        <PropertyName>PSParentPath</PropertyName>
        <CustomControl>
          <CustomEntries>
            <CustomEntry>
              <CustomItem>
                <ExpressionBinding>
                  <ScriptBlock>
${header}
                  </ScriptBlock>
                </ExpressionBinding>
              </CustomItem>
            </CustomEntry>
          </CustomEntries>
        </CustomControl>
      </GroupBy>
      <TableControl>
        <TableHeaders>
          <TableColumnHeader>
            <Label>Mode</Label>
            <Width>7</Width>
            <Alignment>Left</Alignment>
          </TableColumnHeader>
          <TableColumnHeader>
            <Label>LastWriteTime</Label>
            <Width>26</Width>
            <Alignment>Right</Alignment>
          </TableColumnHeader>
          <TableColumnHeader>
            <Label>Length</Label>
            <Width>14</Width>
            <Alignment>Right</Alignment>
          </TableColumnHeader>
          <TableColumnHeader>
            <Label>Name</Label>
            <Alignment>Left</Alignment>
          </TableColumnHeader>
        </TableHeaders>
        <TableRowEntries>
          <TableRowEntry>
            <Wrap />
            <TableColumnItems>
${item(mode)}
${item(lastWrite)}
${item(length)}
${item(name)}
            </TableColumnItems>
          </TableRowEntry>
        </TableRowEntries>
      </TableControl>
    </View>
  </ViewDefinitions>
</Configuration>
`
}
